"""Freeze separate RAW boundaries after implementation, before boundary runtime.

No product, renderer or measured output supplies rectangles, aliases or truth.
The original 43 inputs/criteria are read-only; two source PDFs are newly authored.
Use pinned Python -B. --verify-existing compares every generated byte in memory.
"""

import argparse
import copy
import hashlib
import io
import json
from pathlib import Path

from pypdf import PdfReader, PdfWriter
from pypdf.generic import NameObject
from prepare_redaction_helpers import stream

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "fixtures/redaction-copy/mixed-word-spacing-v1"
PIN = "bcf6e229e6f487d6287acb6962791dca8bc34a91857e16d1eb0c8e4ba6cdaa2e"


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def generate(folder, verify):
    raw = (BASE / "criteria-v3.json").read_bytes()
    assert sha(raw) == PIN
    criteria = json.loads(raw)
    original = criteria["cases"][0]
    original_data = (BASE / original["file"]).read_bytes()
    assert sha(original_data) == original["sha256"]
    source_path = (BASE / original["file"]).relative_to(ROOT).as_posix()

    def save(name, data):
        target = folder / name
        if verify or target.exists():
            assert target.read_bytes() == data, name
        else:
            with target.open("xb") as handle:
                handle.write(data)

    rows = []
    shows = original["font_bindings"][0]["streams"]
    for name, show_index, entry_index in (
        ("first-glyph", 0, 0),
        ("last-glyph", len(shows) - 1, 3),
    ):
        selected = shows[show_index]["entries"][entry_index]
        low, bottom, high, top = selected["outline_box_pt"]
        rect = [low - 1, bottom - 1, high - low + 2, top - bottom + 2]
        selected_paths = []
        for si, show in enumerate(shows):
            for ei, entry in enumerate(show["entries"]):
                box = entry["outline_box_pt"]
                if not box:
                    continue
                disjoint = (
                    box[2] <= rect[0]
                    or box[0] >= rect[0] + rect[2]
                    or box[3] <= rect[1]
                    or box[1] >= rect[1] + rect[3]
                )
                covered = (
                    rect[0] <= box[0] <= box[2] <= rect[0] + rect[2]
                    and rect[1] <= box[1] <= box[3] <= rect[1] + rect[3]
                )
                assert disjoint or covered, (name, si, ei)
                if covered:
                    selected_paths.append([si, ei])
        assert selected_paths == [[show_index, entry_index]]
        rows.append(
            dict(
                name=name,
                source=source_path,
                sha256=sha(original_data),
                refused=True,
                expected_guard="RAW first/last actual glyph frame",
                message_contains="先頭や末尾",
                rect=rect,
                source_selected_glyphs=selected_paths,
                source_selected_entry=selected,
                output=name + ".pdf",
            )
        )

    primary_keys = sorted(
        {e["code_hex"] for show in shows for e in show["entries"] if not e["removed"]}
    )
    assert len(primary_keys) == 7
    public = next(x for x in original["encoding_route"] if x["code_hex"] == "41")
    assert public["cid"] == 300
    for used in (256, 257):
        alias_count = used - len(primary_keys)
        aliases = [(0x8200 + i).to_bytes(2, "big") for i in range(alias_count)]
        assert all(int.from_bytes(x, "big") > 255 for x in aliases)
        encoding = (
            original["encoding_bytes"]
            .encode()
            .replace(b"<8100> <81ff>", b"<8100> <83ff>")
        )
        unicode = (
            original["tounicode_bytes"]
            .encode()
            .replace(b"<8100> <81ff>", b"<8100> <83ff>")
        )
        enc_rows = b"".join(b"<" + x.hex().encode() + b"> 300\n" for x in aliases)
        uni_rows = b"".join(b"<" + x.hex().encode() + b"> <516c>\n" for x in aliases)
        encoding = encoding.replace(
            b"endcmap",
            str(alias_count).encode()
            + b" begincidchar\n"
            + enc_rows
            + b"endcidchar\nendcmap",
        )
        unicode = unicode.replace(
            b"endcmap",
            str(alias_count).encode()
            + b" beginbfchar\n"
            + uni_rows
            + b"endbfchar\nendcmap",
        )
        writer = PdfWriter(clone_from=PdfReader(io.BytesIO(original_data)))
        page = writer.pages[0]
        font = next(
            v.get_object()
            for v in page["/Resources"]["/Font"].values()
            if "/DescendantFonts" in v.get_object()
        )
        font[NameObject("/Encoding")] = writer._add_object(stream(encoding))
        font[NameObject("/ToUnicode")] = writer._add_object(stream(unicode))
        content = original["content_bytes"].encode()
        alias_shows = []
        for start in range(0, alias_count, 16):
            items = aliases[start : start + 16]
            y = 350 - (start // 16) * 12
            glyphs = b"".join(items)
            content += (
                b"BT /F2+0 9 Tf 3.25 Tw 1.25 Tc 85 Tz 0 Ts 1 0 0 1 60 "
                + str(y).encode()
                + b" Tm <"
                + glyphs.hex().encode()
                + b"> Tj ET\n"
            )
            alias_shows.append(
                dict(
                    origin_pt=[60, y],
                    font_size_pt=9,
                    tw=3.25,
                    tc=1.25,
                    horizontal_scale=0.85,
                    code_hex=[x.hex() for x in items],
                    unicode="公" * len(items),
                    per_glyph_advance_pt=(9 + 1.25) * 0.85,
                )
            )
        page[NameObject("/Contents")] = writer._add_object(stream(content))
        buffer = io.BytesIO()
        writer.write(buffer)
        data = buffer.getvalue()
        name = "used-codekeys-" + str(used)
        save(name + ".pdf", data)
        fresh = PdfReader(io.BytesIO(data))
        fresh_font = next(
            v.get_object()
            for v in fresh.pages[0]["/Resources"]["/Font"].values()
            if "/DescendantFonts" in v.get_object()
        )
        sfnt = (
            fresh_font["/DescendantFonts"][0]
            .get_object()["/FontDescriptor"]["/FontFile2"]
            .get_data()
        )
        assert sha(sfnt) == original["source_sfnt_sha256"]
        rows.append(
            dict(
                name=name,
                source=(folder / (name + ".pdf")).relative_to(ROOT).as_posix(),
                sha256=sha(data),
                refused=used == 257,
                expected_guard=(
                    "RAW builder route-count >256"
                    if used == 257
                    else "RAW256 own-decoder roundtrip"
                ),
                message_contains="TrueType" if used == 257 else "",
                rect=original["rect"],
                output=name + ".pdf",
                used_codekey_count=used,
                source_codespace_count=2,
                source_mapping_rows=13 + alias_count,
                source_sfnt_sha256=sha(sfnt),
                encoding_sha256=sha(encoding),
                tounicode_sha256=sha(unicode),
                content_sha256=sha(content),
                primary_retained_keys=primary_keys,
                alias_codes=[x.hex() for x in aliases],
                alias_cid=300,
                alias_gid=public["gid"],
                alias_unicode="公",
                alias_shows=alias_shows,
                remove=original["remove"],
                keep=original["keep"],
                exact_final_used_keys=sorted(primary_keys + [x.hex() for x in aliases]),
            )
        )
    fixed = dict(
        format="dev43-RAW-boundary-controls-v1",
        chronology="Fixed after RAW guard implementation/staticreview; before boundary product runtime. Never preimplementation.",
        main_43_criteria=dict(
            path="fixtures/redaction-copy/mixed-word-spacing-v1/criteria-v3.json",
            sha256=PIN,
            unchanged=True,
        ),
        cases=rows,
        position_error_pt=0.5,
        boundary_pixels=1,
        outside_pixel_difference=0,
        dpi=[72, 96, 300],
        direct_builder=dict(
            source=source_path,
            sha256=sha(original_data),
            source_sfnt_sha256=original["source_sfnt_sha256"],
            glyph=dict(cid=public["cid"], gid=public["gid"], unicode="公", width=1000),
            valid_keys=["41"]
            + [(0x8200 + i).to_bytes(2, "big").hex() for i in range(255)],
            invalid_keys=["41"]
            + [(0x8200 + i).to_bytes(2, "big").hex() for i in range(256)],
            valid_count=256,
            invalid_count=257,
            expected_guard="optional builder pre-subset route limit",
        ),
        runtime_passes=0,
        general_M1_M3_M5_acceptance="withheld",
    )
    blob = (
        json.dumps(fixed, ensure_ascii=False, separators=(",", ":")) + "\n"
    ).encode()
    save("criteria.json", blob)
    assert (BASE / "criteria-v3.json").read_bytes() == raw
    total = sum(p.stat().st_size for p in folder.iterdir())
    assert total < 160000, total
    return dict(
        cases=4, new_pdfs=2, bytes=total, criteria_sha256=sha(blob), runtime_passes=0
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--verify-existing", action="store_true")
    args = parser.parse_args()
    folder = args.output.resolve()
    folder.relative_to(ROOT)
    if not args.verify_existing:
        folder.mkdir(exist_ok=False)
    print(json.dumps(generate(folder, args.verify_existing)))


if __name__ == "__main__":
    main()
